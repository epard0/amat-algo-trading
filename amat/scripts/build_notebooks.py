"""Author the research notebooks programmatically.

The notebooks under ``notebooks/`` are generated by this script rather than
hand-edited, for the same reason reports are rendered from run artifacts: a
notebook whose provenance is "someone edited JSON until it looked right" can
drift from the library APIs it demonstrates. Regenerate (and re-execute) with:

    uv run --group notebooks python scripts/build_notebooks.py
    uv run --group notebooks python scripts/execute_notebooks.py

Cells deliberately run on a REDUCED sample window (2021 onward) so an
execution costs minutes; the canonical full-sample entry points are the
``amat`` CLI commands, which persist run records.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import nbformat

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "notebooks"

KERNEL: dict[str, Any] = {
    "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
    "language_info": {"name": "python", "version": "3.12"},
}

_SETUP_CELL = """\
# Locate the repository root whether this kernel started in notebooks/ or the root.
import datetime as dt
from pathlib import Path

ROOT = Path.cwd() if (Path.cwd() / "configs").exists() else Path.cwd().parent
assert (ROOT / "configs" / "strategy" / "amat_v1.toml").exists(), ROOT

import matplotlib
matplotlib.use("Agg")  # headless-safe; inline display still works
import matplotlib.pyplot as plt
import numpy as np
import polars as pl

from amat.config.loading import load_strategy_config
from amat.data.snapshot import load_corporate_actions, load_panel

SNAPSHOT = ROOT / "data" / "snapshots" / "alpaca-sip-2026-08-11"
resolved = load_strategy_config(ROOT / "configs" / "strategy" / "amat_v1.toml")
strategy = resolved.strategy
symbols = [str(s) for s in strategy.universe.symbols]

# A reduced window keeps every notebook run affordable (minutes, not an hour).
# The CLI commands run the full sample and persist run records; this notebook
# demonstrates the same machinery through the library API.
START = dt.date(2021, 1, 4)
panel, manifest = load_panel(SNAPSHOT, symbols, start=START)
actions = load_corporate_actions(SNAPSHOT, symbols, sessions=panel.sessions)
print(f"snapshot {manifest.snapshot_id}: {len(panel)} sessions from {panel.sessions[0]}")
print(f"config {resolved.content_sha256[:16]}  strategy {strategy.name} v{strategy.version}")
"""


def _monte_carlo_notebook() -> nbformat.NotebookNode:
    notebook = nbformat.v4.new_notebook()
    notebook.metadata.update(KERNEL)
    notebook.cells = [
        nbformat.v4.new_markdown_cell(
            "# Monte Carlo robustness study\n"
            "\n"
            "The strategy's one measured history is a single draw. This notebook uses\n"
            "the repository's stationary block-bootstrap machinery\n"
            "(`amat.validation.montecarlo`) to resample the market panel's own joint\n"
            "session moves into alternative markets, run the **frozen v1 core** on\n"
            "each, and place the observed result inside the resampled distribution.\n"
            "\n"
            "**What this is not.** A forecast. The bootstrap preserves cross-sectional\n"
            "structure exactly and short-horizon clustering approximately, but it\n"
            "breaks dependence longer than its blocks — which is conservative for a\n"
            "trend strategy, whose premium (if any) *is* long memory. Probabilities\n"
            "below describe the resampled worlds only.\n"
            "\n"
            "*Backtest research only; nothing here is investment advice or a\n"
            "live-trading signal. The canonical, full-sample, record-persisting entry\n"
            "point is `amat montecarlo` — this notebook is the same machinery on a\n"
            "reduced window so it executes in minutes.*"
        ),
        nbformat.v4.new_code_cell(_SETUP_CELL),
        nbformat.v4.new_markdown_cell(
            "## One resampled market\n"
            "\n"
            "A resampled session is one whole cross-sectional row of per-symbol moves\n"
            "(never a per-symbol shuffle), drawn in geometric-length blocks with mean\n"
            "21 sessions. Same calendar, same starting prices; dividends live inside\n"
            "the price path, so the resampled world carries no separate corporate\n"
            "actions."
        ),
        nbformat.v4.new_code_cell(
            """\
from amat.validation.montecarlo import bootstrap_panel

spy = symbols.index("SPY")
fig, ax = plt.subplots(figsize=(10, 4.5))
for seed in (1, 2, 3):
    resampled = bootstrap_panel(panel, seed=seed)
    ax.plot(panel.sessions,
            resampled.adjusted_closes[:, spy] / resampled.adjusted_closes[0, spy],
            linewidth=0.9, alpha=0.7, label=f"resampled (seed {seed})")
ax.plot(panel.sessions, panel.adjusted_closes[:, spy] / panel.adjusted_closes[0, spy],
        color="black", linewidth=1.8, label="observed SPY")
ax.set_title("SPY, observed vs three bootstrap worlds (growth of 1, adjusted)")
ax.legend(fontsize=8, frameon=False)
ax.grid(alpha=0.3)
plt.show()"""
        ),
        nbformat.v4.new_markdown_cell(
            "## The study\n"
            "\n"
            "Each path is a full engine run — warm-up, next-open VWAP execution,\n"
            "2 bps one-way costs, accounting identity — on one resampled market.\n"
            "Path *i* uses seed `base + i`, so any path can be regenerated alone and\n"
            "the study reproduces bit-for-bit at any worker count."
        ),
        nbformat.v4.new_code_cell(
            """\
from decimal import Decimal
from amat.validation.montecarlo import run_monte_carlo

study = run_monte_carlo(
    strategy,
    panel,
    strategy.to_universe(),
    paths=16,                    # the CLI runs 200; 16 keeps the notebook to minutes
    seed=20260812,
    initial_cash=Decimal("100000"),
    actions_by_session=actions,  # the observed run credits real dividends/splits
    workers=4,
    progress=print,
)
print()
print(study.caveat)"""
        ),
        nbformat.v4.new_code_cell(
            """\
# Equity fan: percentile bands of the resampled paths, observed curve overlaid.
fig, ax = plt.subplots(figsize=(10, 4.5))
dates = list(study.band_dates)
ax.fill_between(dates, study.equity_bands["p05"], study.equity_bands["p95"],
                color="#c7d8ec", linewidth=0, label="resampled 5th-95th pct")
ax.fill_between(dates, study.equity_bands["p25"], study.equity_bands["p75"],
                color="#8fb4dc", linewidth=0, label="resampled 25th-75th pct")
ax.plot(dates, study.equity_bands["p50"], "--", color="#2f6db3", linewidth=1.1,
        label="resampled median")
ax.plot(dates, study.observed_equity, color="black", linewidth=1.8, label="observed")
ax.axhline(study.initial_cash, color="grey", linewidth=0.8, linestyle=":")
ax.set_title(f"Equity fan - {study.strategy}, {study.paths} bootstrap paths")
ax.legend(fontsize=8, frameon=False)
ax.grid(alpha=0.3)
plt.show()"""
        ),
        nbformat.v4.new_code_cell(
            """\
# The distribution table the CLI's PDF renders, as a DataFrame.
rows = []
for metric, pcts in study.metric_percentiles.items():
    rows.append({
        "metric": metric,
        **{k: round(v, 4) for k, v in pcts.items()},
        "observed": round(getattr(study.observed, metric), 4),
        "obs_percentile": round(study.observed_percentile[metric], 2),
    })
table = pl.DataFrame(rows)
print(table)
print()
for name, value in study.probabilities.items():
    print(f"P[{name}] = {value:.1%} of resampled paths")"""
        ),
        nbformat.v4.new_markdown_cell(
            "## Reading the result honestly\n"
            "\n"
            "- An observed metric sitting **above** most resampled paths means the\n"
            "  real ordering of history (long trends the blocks destroy) — or luck —\n"
            "  carried it; the bootstrap cannot distinguish those two.\n"
            "- The exceedance probabilities are *within-resampling* frequencies, not\n"
            "  probabilities about the future.\n"
            "- The full-sample, 200-path study with a persisted run record and a PDF:\n"
            "\n"
            "```bash\n"
            "uv run amat montecarlo configs/strategy/amat_v1.toml \\\n"
            "  --snapshot data/snapshots/alpaca-sip-2026-08-11 \\\n"
            "  --paths 200 --pdf outputs/reports/amat_v1_montecarlo.pdf\n"
            "```"
        ),
    ]
    return notebook


def _walk_forward_notebook() -> nbformat.NotebookNode:
    notebook = nbformat.v4.new_notebook()
    notebook.metadata.update(KERNEL)
    notebook.cells = [
        nbformat.v4.new_markdown_cell(
            "# Walk-forward folds and market regimes\n"
            "\n"
            "The frozen v1 core fits nothing across runs, so an expanding\n"
            "walk-forward reduces to **one** full-history run whose equity curve is\n"
            "sliced into calendar folds (`amat.validation.walkforward`). Fold\n"
            "dispersion measures *consistency* — whether the aggregate was earned\n"
            "across years or granted by one of them. It is **not** out-of-sample\n"
            "evidence: this configuration was frozen after the history below was\n"
            "known; untouched data begins only after the declared holdout boundary\n"
            "(`outputs/holdouts/`).\n"
            "\n"
            "*Backtest research only. The record-persisting entry point is\n"
            "`amat walkforward`; this notebook demonstrates the same machinery on a\n"
            "reduced window.*"
        ),
        nbformat.v4.new_code_cell(_SETUP_CELL),
        nbformat.v4.new_code_cell(
            """\
from decimal import Decimal
from amat.validation.walkforward import walk_forward

result = walk_forward(
    strategy,
    panel,
    strategy.to_universe(),
    initial_cash=Decimal("100000"),
    actions_by_session=actions,
)
folds = pl.DataFrame([
    {
        "fold": fold.label,
        "sessions": fold.statistics.sessions,
        "total_return": round(fold.statistics.total_return, 4),
        "annualized": round(fold.statistics.annualized_return, 4),
        "volatility": round(fold.statistics.annualized_volatility, 4),
        "sharpe": round(fold.statistics.sharpe, 2),
        "max_drawdown": round(fold.statistics.max_drawdown, 4),
        "trades": fold.statistics.trades,
    }
    for fold in result.folds
])
print(folds)
print()
print(f"positive folds: {result.positive_fold_fraction:.0%}")
print(f"full sample: sharpe {result.full_sample.sharpe:.2f}, "
      f"max drawdown {result.full_sample.max_drawdown:.2%}")
print()
print("!", result.caveat)"""
        ),
        nbformat.v4.new_code_cell(
            """\
fig, ax = plt.subplots(figsize=(8, 3.5))
labels = [fold.label for fold in result.folds]
sharpes = [fold.statistics.sharpe for fold in result.folds]
colors = ["#2f7fd1" if s >= 0 else "#c62828" for s in sharpes]
ax.bar(labels, sharpes, color=colors)
ax.axhline(0, color="black", linewidth=0.8)
ax.set_title("Per-fold Sharpe - consistency, not out-of-sample proof")
ax.grid(axis="y", alpha=0.3)
plt.show()

for gate in result.research_gates():
    status = "PASS" if gate.passed else ("FAIL" if gate.measurable else "NOT MEASURABLE")
    print(f"[{status}] {gate.name}: {gate.measured} (limit {gate.limit})")
print("(necessary, never sufficient - see .claude/references/promotion-gates.md)")"""
        ),
        nbformat.v4.new_markdown_cell(
            "## Performance by market regime\n"
            "\n"
            "Sessions are labelled causally from SPY's own past — trailing 63-session\n"
            "return sign (bull/bear) x trailing 21-session realized volatility\n"
            "against its expanding median (quiet/volatile). The labels condition\n"
            "nothing; they only describe where the run's session returns landed.\n"
            "Session `t`'s return is booked under session `t-1`'s label: the label\n"
            "at `t` contains `t`'s own move, and the contemporaneous convention\n"
            "manufactures a ~1.27x quiet/volatile separation on pure noise.\n"
            "Per-regime drawdowns are undefined (the sessions are interleaved) and\n"
            "deliberately absent."
        ),
        nbformat.v4.new_code_cell(
            """\
from amat.validation.regimes import classify_sessions, regime_performance

labels = classify_sessions(panel)
slices = regime_performance(result.equity_curve, result.session_dates, panel, labels)
regimes = pl.DataFrame([
    {
        "regime": entry.label,
        "sessions": entry.sessions,
        "share": round(entry.share_of_sample, 3),
        "annualized": round(entry.annualized_return, 4),
        "volatility": round(entry.annualized_volatility, 4),
        "sharpe": round(entry.sharpe, 2),
        "hit_rate": round(entry.hit_rate, 2),
    }
    for entry in slices
])
print(regimes)"""
        ),
        nbformat.v4.new_markdown_cell(
            "## Caveats, restated\n"
            "\n"
            "- One frozen configuration, one vendor's data, one decade. Fold and\n"
            "  regime tables describe this sample; they do not forecast.\n"
            "- The 2021 start date here exists to keep the notebook fast; the\n"
            "  canonical full-sample numbers live in the persisted run records under\n"
            "  `outputs/runs/` and in `docs/experiment-registry.md`.\n"
            "- Regime conditioning as a *strategy input* is a registered experiment\n"
            "  (`amat regime-experiment`) judged by falsification controls — see the\n"
            "  registry for verdicts before drawing any conclusion from these\n"
            "  slices."
        ),
    ]
    return notebook


def main() -> None:
    OUT.mkdir(exist_ok=True)
    nbformat.write(_monte_carlo_notebook(), OUT / "monte_carlo_study.ipynb")
    nbformat.write(_walk_forward_notebook(), OUT / "walk_forward_and_regimes.ipynb")
    print("written:", ", ".join(sorted(path.name for path in OUT.glob("*.ipynb"))))


if __name__ == "__main__":
    main()
